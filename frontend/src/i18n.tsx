const UNITS_RU: Record<string, string> = {
  fraction: 'доля',
  'mm/day': 'мм/сут',
  'g/kg': 'г/кг',
  'kg/m²': 'кг/м²',
  'm/s': 'м/с',
  hPa: 'гПа',
  DU: 'е. Д.',
  cm: 'см',
  'W/m²': 'Вт/м²',
  mm: 'мм',
  '10¹⁵ molec/cm²': '10¹⁵ молек./см²',
}

export type Key = keyof typeof EN
const DICT: Record<Lang, typeof EN> = { en: EN, ru: RU }

function detect(): Lang {
  const forced = new URLSearchParams(location.search).get('lang')
  if (forced === 'ru' || forced === 'en') return forced
  const saved = localStorage.getItem('lang')
  if (saved === 'ru' || saved === 'en') return saved
  return navigator.language.toLowerCase().startsWith('ru') ? 'ru' : 'en'
}

type Ctx = {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: Key, vars?: Record<string, string | number>) => string
  l: (x: L10n | null | undefined) => string
  num: (v: number | null | undefined, decimals?: number, signed?: boolean) => string
  unit: (units: string) => string
}
const LangContext = createContext<Ctx | null>(null)

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setState] = useState<Lang>(detect)
  const setLang = useCallback((l: Lang) => {
    localStorage.setItem('lang', l)
    document.documentElement.lang = l
    setState(l)
  }, [])
  const value = useMemo<Ctx>(() => {
    const t = (key: Key, vars?: Record<string, string | number>) => DICT[lang][key].replace(/\{(\w+)\}/g, (_, k) => String(vars?.[k] ?? ''))
    const l = (x: L10n | null | undefined) => (x ? x[lang] || x.en : '')
    const num = (v: number | null | undefined, decimals = 2, signed = false) => {
      if (v === null || v === undefined || !Number.isFinite(v)) return '·'
      const s = new Intl.NumberFormat(lang === 'ru' ? 'ru-RU' : 'en-US', {
        minimumFractionDigits: decimals,
        maximumFractionDigits: decimals,
      }).format(Math.abs(v))
      // typographic minus, not a hyphen
      return (v < 0 ? '\u2212' : signed && v > 0 ? '+' : '') + s
    }
    const unit = (units: string) => (lang === 'ru' ? (UNITS_RU[units] ?? units) : units)
    return { lang, setLang, t, l, num, unit }
  }, [lang, setLang])
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>
}

export function useI18n(): Ctx {
  const c = useContext(LangContext)
  if (!c) throw new Error('useI18n outside LangProvider')
  return c
}
